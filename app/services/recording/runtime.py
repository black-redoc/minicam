"""Process-wide event recording wiring shared by main.py and the routers.

Like app.services.notifications.runtime, this holds singletons. Settings are
read on every decision, so switching recording on or off (or changing the
storage limit) in the Admin page applies without restarting any camera.

Threads involved, and how they meet:

- Capture threads (one per camera) feed their CameraRecorder and, through
  _open_clip(), start a ClipWriter per clip.
- Clip writer threads report each finished clip via _on_clip_finished(),
  which schedules _register() on the event loop.
- The event loop owns the database: it records clips, applies retention
  and turns detection snapshots into recording deadlines.
"""

from __future__ import annotations

import asyncio
import concurrent.futures
import logging
import secrets
import threading
import time
from collections.abc import Callable
from pathlib import Path

import aiosqlite

from app.db.connection import get_connection
from app.models.config import RecordingConfig
from app.models.domain import Recording
from app.repositories.recording_repository import SQLiteRecordingRepository
from app.services.detection.worker import DetectionSnapshot
from app.services.recording import storage
from app.services.recording.packets import ClipSink, ClipStart
from app.services.recording.recorder import PRE_ROLL_SECONDS, CameraRecorder
from app.services.recording.trigger import RecordingTrigger
from app.services.recording.writer import PART_SUFFIX, ClipWriter, FinishedClip
from app.settings import get_config

logger = logging.getLogger(__name__)

RECORDINGS_DIR = Path(__file__).resolve().parent.parent.parent / "data" / "recordings"
_CLIP_SUFFIX = ".mp4"
_WRITER_JOIN_TIMEOUT_SECONDS = 10.0
_LOW_SPACE_WARNING_INTERVAL_SECONDS = 60.0

WriterOpener = Callable[
    [ClipStart, Path, Callable[[FinishedClip], None]], ClipWriter | None
]


class RecordingService:
    """Owns every camera's recorder and the lifecycle of finished clips."""

    def __init__(
        self,
        recordings_dir: Path,
        connection: Callable[[], aiosqlite.Connection],
        config: Callable[[], RecordingConfig],
        open_writer: WriterOpener = ClipWriter.open,
        get_free_bytes: Callable[[Path], int] = storage.free_bytes,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self._dir = recordings_dir
        self._connection = connection
        self._config = config
        self._open_writer = open_writer
        self._get_free_bytes = get_free_bytes
        self._clock = clock
        self._loop: asyncio.AbstractEventLoop | None = None
        self._recorders: dict[str, CameraRecorder] = {}
        self._triggers: dict[str, RecordingTrigger] = {}
        # Touched from capture threads (writers) and writer threads (pending).
        self._lock = threading.Lock()
        self._writers: list[ClipWriter] = []
        self._pending: set[concurrent.futures.Future[None]] = set()
        self._retention_lock = asyncio.Lock()
        self._last_low_space_warning = -_LOW_SPACE_WARNING_INTERVAL_SECONDS

    @property
    def recordings_dir(self) -> Path:
        return self._dir

    def _repository(self) -> SQLiteRecordingRepository:
        return SQLiteRecordingRepository(self._connection())

    def free_bytes(self) -> int:
        return self._get_free_bytes(self._dir)

    def path_for(self, recording: Recording) -> Path:
        """The clip's file. file_name is generated by minicam, but is still
        checked to be a bare name so a bad row can never point elsewhere."""
        name = recording.file_name
        if Path(name).name != name or not name.endswith(_CLIP_SUFFIX):
            raise ValueError(f"Invalid recording file name: {name!r}")
        return self._dir / name

    # ── Lifecycle ───────────────────────────────────────────────────────

    async def start(self) -> None:
        """Bind to the running loop and reconcile disk with the database."""
        self._loop = asyncio.get_running_loop()
        repository = self._repository()
        known = await repository.list_file_names()
        on_disk = await asyncio.to_thread(self._scan_and_clean, known)
        for file_name in known - on_disk:
            await repository.delete_by_file_name(file_name)
        await self.enforce_retention()

    def _scan_and_clean(self, known: set[str]) -> set[str]:
        """Delete unfinished (.part) and unregistered clips; return the rest."""
        self._dir.mkdir(parents=True, exist_ok=True)
        kept: set[str] = set()
        for path in self._dir.iterdir():
            if not path.is_file():
                continue
            if path.name.endswith(_CLIP_SUFFIX + PART_SUFFIX) or (
                path.name.endswith(_CLIP_SUFFIX) and path.name not in known
            ):
                logger.info("Removing incomplete recording %s", path.name)
                path.unlink(missing_ok=True)
            elif path.name.endswith(_CLIP_SUFFIX):
                kept.add(path.name)
        return kept

    async def shutdown(self) -> None:
        """Wait for clips being written (cameras must be stopped first)."""
        with self._lock:
            writers = list(self._writers)
        await asyncio.to_thread(self._join_writers, writers)
        with self._lock:
            pending = list(self._pending)
        await asyncio.gather(
            *(asyncio.wrap_future(f) for f in pending), return_exceptions=True
        )
        self._loop = None

    @staticmethod
    def _join_writers(writers: list[ClipWriter]) -> None:
        for writer in writers:
            if not writer.join(_WRITER_JOIN_TIMEOUT_SECONDS):
                logger.warning("A recording did not finish writing in time")

    # ── Cameras ─────────────────────────────────────────────────────────

    def recorder_for(self, camera_name: str) -> CameraRecorder:
        """Create the recorder for a camera that is (re)starting."""
        recorder = CameraRecorder(camera_name, self._open_clip)
        self._recorders[camera_name] = recorder
        return recorder

    def forget(self, camera_name: str) -> None:
        """Drop a camera's state (it was deleted or renamed)."""
        self._recorders.pop(camera_name, None)
        self._triggers.pop(camera_name, None)

    def on_snapshot(self, camera_name: str, snapshot: DetectionSnapshot) -> None:
        recorder = self._recorders.get(camera_name)
        if recorder is None:
            return
        enabled = self._config().enabled
        recorder.arm(enabled)
        if not enabled:
            return
        trigger = self._triggers.setdefault(camera_name, RecordingTrigger())
        deadline = trigger.on_snapshot(snapshot, self._clock())
        if deadline is not None:
            recorder.record_until(deadline)

    # ── Capture thread: opening clips ───────────────────────────────────

    def _open_clip(self, start: ClipStart) -> ClipSink | None:
        if self._loop is None:
            return None
        try:
            if self._get_free_bytes(self._dir) < storage.RESERVE_BYTES:
                self._warn_low_space(start.camera_name)
                return None
            file_name = (
                f"{start.started_at:%Y%m%dT%H%M%SZ}-{secrets.token_hex(4)}"
                f"{_CLIP_SUFFIX}"
            )
            writer = self._open_writer(
                start, self._dir / file_name, self._on_clip_finished
            )
        except Exception as exc:
            logger.error(
                "Could not start recording for camera %r: %s: %s",
                start.camera_name,
                type(exc).__name__,
                exc,
            )
            return None
        if writer is not None:
            with self._lock:
                self._writers = [w for w in self._writers if not w.join(0)]
                self._writers.append(writer)
        return writer

    def _warn_low_space(self, camera_name: str) -> None:
        now = self._clock()
        if now - self._last_low_space_warning >= _LOW_SPACE_WARNING_INTERVAL_SECONDS:
            self._last_low_space_warning = now
            logger.warning(
                "Not recording camera %r: less than %d MiB free on disk",
                camera_name,
                storage.RESERVE_BYTES // 1024**2,
            )

    # ── Writer thread → event loop: finished clips ──────────────────────

    def _on_clip_finished(self, clip: FinishedClip) -> None:
        loop = self._loop
        if loop is None:
            return  # registered (or removed) by the next start()'s cleanup
        coroutine = self._register(clip)
        try:
            future = asyncio.run_coroutine_threadsafe(coroutine, loop)
        except RuntimeError:
            coroutine.close()
            return  # loop already closed
        with self._lock:
            self._pending.add(future)
        future.add_done_callback(self._discard_pending)

    def _discard_pending(self, future: concurrent.futures.Future[None]) -> None:
        with self._lock:
            self._pending.discard(future)

    async def _register(self, clip: FinishedClip) -> None:
        trigger = self._triggers.get(clip.camera_name)
        end = self._clock()
        start = end - clip.duration_seconds - PRE_ROLL_SECONDS - 1.0
        classes = trigger.classes_between(start, end) if trigger is not None else ()
        try:
            await self._repository().add(
                camera_name=clip.camera_name,
                file_name=clip.path.name,
                started_at=clip.started_at.isoformat(),
                duration_seconds=clip.duration_seconds,
                size_bytes=clip.size_bytes,
                classes=classes,
            )
            await self.enforce_retention()
        except Exception:
            logger.exception("Could not register recording %s", clip.path.name)

    async def enforce_retention(self) -> int:
        async with self._retention_lock:
            return await storage.enforce_retention(
                self._repository(),
                self._dir,
                self._config().max_storage_gb * storage.GIB,
                self.free_bytes,
            )


service = RecordingService(
    RECORDINGS_DIR,
    connection=get_connection,
    config=lambda: get_config().recordings,
)
